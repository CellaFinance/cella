// Makes the mainnet proving key for the transact circuit.
//
//   node scripts/ceremony.mjs build/ceremony/hez16.ptau
//
// Phase 1 is the public Hermez "powers of tau" ceremony (many independent
// participants); the file is checked against the checksum published by snarkjs.
// Phase 2, which is specific to this circuit, has two steps:
//   1. one contribution with randomness from this machine, used once and never stored;
//   2. a beacon: the hash of a Robinhood Chain block mined after step 1 finished,
//      so nobody, including whoever ran step 1, could have chosen it.
//
// What this does and does not give: the key is sound unless the single phase-2
// contributor kept their randomness. More independent contributors can be added
// later by continuing from build/mainnet/transact_0001.zkey before the beacon.
//
// Writes build/mainnet/transact.zkey, contracts/Groth16VerifierMainnet.sol and
// ceremony/mainnet.json (the public record: every hash needed to check the key).
import * as snarkjs from "snarkjs";
import { createHash, randomBytes } from "node:crypto";
import { execFileSync } from "node:child_process";
import { createReadStream, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./lib/local.mjs";

const PTAU_BLAKE2B = "6a6277a2f74e1073601b4f9fed6e1e55226917efb0f0db8a07d98ab01df1ccf43eb0e8c3159432acd4960e2f29fe84a4198501fa54c8dad9e43297453efec125";
const RPC = "https://rpc.mainnet.chain.robinhood.com";
const BEACON_ITERATIONS_EXP = 10;

const ptau = process.argv[2];
if (!ptau) { console.error("usage: node scripts/ceremony.mjs <powersOfTau28_hez_final_16.ptau>"); process.exit(1); }
const digest = (file, algo) => new Promise((ok, no) => {
  const h = createHash(algo);
  createReadStream(file).on("data", (b) => h.update(b)).on("end", () => ok(h.digest("hex"))).on("error", no);
});
const hex = (bytes) => Buffer.from(bytes).toString("hex");
const rpc = async (method, params) => {
  const r = await fetch(RPC, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ jsonrpc: "2.0", id: 1, method, params }) });
  return (await r.json()).result;
};

if ((await digest(ptau, "blake2b512")) !== PTAU_BLAKE2B) { console.error("the powers-of-tau file does not match the published checksum"); process.exit(1); }
console.log("phase 1 file matches the published checksum");

const out = join(ROOT, "build/mainnet");
mkdirSync(out, { recursive: true });
const r1cs = join(ROOT, "build/transact.r1cs");
const z0 = join(out, "transact_0000.zkey"), z1 = join(out, "transact_0001.zkey"), zf = join(out, "transact.zkey");

await snarkjs.zKey.newZKey(r1cs, ptau, z0);
console.log("circuit key started from phase 1");

// 64 bytes from the operating system, held only in this variable.
const contribution = hex(await snarkjs.zKey.contribute(z0, z1, "Cella operator", randomBytes(64).toString("hex")));
console.log("contribution made");

// The beacon block is chosen only now, after the contribution is fixed on disk.
const z1Hash = await digest(z1, "sha256");
const head = BigInt(await rpc("eth_blockNumber", []));
const beaconBlock = head + 20n;
let block = null;
while (!block) { block = await rpc("eth_getBlockByNumber", ["0x" + beaconBlock.toString(16), false]); if (!block) await new Promise((r) => setTimeout(r, 1000)); }
const beacon = block.hash.slice(2);
await snarkjs.zKey.beacon(z1, zf, "Robinhood Chain block " + beaconBlock, beacon, BEACON_ITERATIONS_EXP);
console.log(`beacon applied: block ${beaconBlock}`);

// Checked by the snarkjs command itself, in a process of its own: the same check anyone else would run.
const verdict = execFileSync(join(ROOT, "node_modules/.bin/snarkjs"), ["zkey", "verify", r1cs, ptau, zf], { encoding: "utf8", maxBuffer: 1 << 26 });
if (!verdict.includes("ZKey Ok!")) { console.error("the finished key does not verify against the circuit"); process.exit(1); }
console.log("finished key verifies against the circuit and phase 1");

const vkey = await snarkjs.zKey.exportVerificationKey(zf);
const template = readFileSync(join(ROOT, "node_modules/snarkjs/templates/verifier_groth16.sol.ejs"), "utf8");
const sol = (await snarkjs.zKey.exportSolidityVerifier(zf, { groth16: template })).replace("contract Groth16Verifier", "contract Groth16VerifierMainnet");
writeFileSync(join(ROOT, "contracts/Groth16VerifierMainnet.sol"),
  "// GENERATED by scripts/ceremony.mjs. Phase 1: public Hermez ceremony. Phase 2: one contribution and a chain beacon.\n// The record is in ceremony/mainnet.json.\n" + sol);

mkdirSync(join(ROOT, "ceremony"), { recursive: true });
writeFileSync(join(ROOT, "ceremony/mainnet.json"), JSON.stringify({
  circuit: "transact", r1csSha256: await digest(r1cs, "sha256"),
  phase1: { file: "powersOfTau28_hez_final_16.ptau", source: "https://circom.info/powersOfTau28_hez_final_16.ptau", blake2b: PTAU_BLAKE2B },
  phase2: [
    { step: 1, kind: "contribution", name: "Cella operator", contributionHash: contribution, keyAfterSha256: z1Hash },
    { step: 2, kind: "beacon", chainId: 4663, block: beaconBlock.toString(), blockHash: block.hash, iterationsExp: BEACON_ITERATIONS_EXP,
      note: "block number fixed after step 1 was written; 20 blocks ahead of the head at that moment" },
  ],
  finalKeySha256: await digest(zf, "sha256"),
  verificationKey: vkey,
  check: "snarkjs zkey verify build/transact.r1cs powersOfTau28_hez_final_16.ptau transact.zkey",
}, null, 2) + "\n");
console.log("written: build/mainnet/transact.zkey, contracts/Groth16VerifierMainnet.sol, ceremony/mainnet.json");
process.exit(0);
