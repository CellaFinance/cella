// Writes src/abi.mjs from the compiled contracts, so the client never drifts from them.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, artifact } from "./lib/local.mjs";
const out = `// GENERATED by scripts/export-abi.mjs. Do not edit.
export const poolAbi = ${JSON.stringify(artifact("CellaPool", "CellaPool").abi)};
export const registryAbi = ${JSON.stringify(artifact("CellaRegistry", "CellaRegistry").abi)};
`;
writeFileSync(join(ROOT, "src/abi.mjs"), out);
console.log("src/abi.mjs written");
