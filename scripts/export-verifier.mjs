// Writes contracts/Groth16Verifier.sol from a proving key.
// Usage: node scripts/export-verifier.mjs [path/to/key.zkey]
// The default key is the local test key. The verifier for mainnet must be
// exported again from the key that comes out of the public ceremony.
import * as snarkjs from "snarkjs";
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const zkey = process.argv[2] ?? join(root, "build/bench/g16.zkey");
const template = readFileSync(join(root, "node_modules/snarkjs/templates/verifier_groth16.sol.ejs"), "utf8");
const code = await snarkjs.zKey.exportSolidityVerifier(zkey, { groth16: template });
const note = "// GENERATED by scripts/export-verifier.mjs from a LOCAL TEST KEY. Not for mainnet.\n";
writeFileSync(join(root, "contracts/Groth16Verifier.sol"), note + code);
console.log("contracts/Groth16Verifier.sol written from", zkey);
process.exit(0);
